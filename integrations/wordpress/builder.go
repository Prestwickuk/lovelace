package wordpress

import (
	"archive/zip"
	"bytes"
	"embed"
	"fmt"
	"io/fs"
	"net/url"
	"regexp"
	"sort"
	"strings"
	"time"

	"github.com/tirbach/tir-bach/internal/branding"
)

//go:embed lovelace-booking
var pluginFS embed.FS

var safeSlugRe = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,63}$`)

// BundleConfig holds pre-populated property defaults injected into the downloadable WordPress plugin .zip.
type BundleConfig struct {
	BookingOrigin  string
	PropertySlug   string
	PropertyName   string
	PrimaryColor   string
	PrimaryOnColor string
}

// BuildPluginZip packages lovelace-booking/* into a ready-to-upload WordPress plugin .zip archive
// with includes/bundled-defaults.php pre-configured for the given property.
func BuildPluginZip(cfg BundleConfig) (zipBytes []byte, filename string, err error) {
	origin := normalizeOrigin(cfg.BookingOrigin)
	slug := strings.ToLower(strings.TrimSpace(cfg.PropertySlug))
	if !safeSlugRe.MatchString(slug) {
		slug = ""
	}
	propName := sanitizeSingleLine(cfg.PropertyName, 120)

	primaryHex, perr := branding.NormalizeOptionalHex("primary", cfg.PrimaryColor)
	if perr != nil || primaryHex == "" {
		primaryHex = "#2F4F4A"
	}
	primaryOnHex, oerr := branding.NormalizeOptionalHex("primary_on", cfg.PrimaryOnColor)
	if oerr != nil || primaryOnHex == "" {
		primaryOnHex = "#FFFFFF"
	}

	var paths []string
	err = fs.WalkDir(pluginFS, "lovelace-booking", func(path string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if d.IsDir() {
			return nil
		}
		paths = append(paths, path)
		return nil
	})
	if err != nil {
		return nil, "", fmt.Errorf("walk embedded wordpress plugin: %w", err)
	}
	sort.Strings(paths)

	fixedModTime := time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)

	for _, p := range paths {
		var content []byte
		if p == "lovelace-booking/includes/bundled-defaults.php" {
			content = []byte(renderBundledDefaultsPHP(origin, slug, propName, primaryHex, primaryOnHex))
		} else {
			content, err = fs.ReadFile(pluginFS, p)
			if err != nil {
				_ = zw.Close()
				return nil, "", fmt.Errorf("read embedded %s: %w", p, err)
			}
		}

		hdr := &zip.FileHeader{
			Name:     p,
			Method:   zip.Deflate,
			Modified: fixedModTime,
		}
		hdr.SetMode(0o644)
		w, werr := zw.CreateHeader(hdr)
		if werr != nil {
			_ = zw.Close()
			return nil, "", fmt.Errorf("create zip entry %s: %w", p, werr)
		}
		if _, werr := w.Write(content); werr != nil {
			_ = zw.Close()
			return nil, "", fmt.Errorf("write zip entry %s: %w", p, werr)
		}
	}

	if err := zw.Close(); err != nil {
		return nil, "", fmt.Errorf("finalize wordpress plugin zip: %w", err)
	}

	suggested := "lovelace-booking.zip"
	if slug != "" {
		suggested = fmt.Sprintf("lovelace-booking-%s.zip", slug)
	}
	return buf.Bytes(), suggested, nil
}

func normalizeOrigin(raw string) string {
	trimmed := strings.TrimRight(strings.TrimSpace(raw), "/")
	if trimmed == "" {
		return ""
	}
	u, err := url.Parse(trimmed)
	if err != nil || u.Scheme == "" || u.Host == "" {
		return ""
	}
	scheme := strings.ToLower(u.Scheme)
	if scheme != "https" && scheme != "http" {
		return ""
	}
	return scheme + "://" + u.Host
}

func sanitizeSingleLine(raw string, maxRunes int) string {
	cleaned := strings.Map(func(r rune) rune {
		if r < 0x20 || r == 0x7f {
			return ' '
		}
		return r
	}, strings.TrimSpace(raw))
	runes := []rune(cleaned)
	if len(runes) > maxRunes {
		runes = runes[:maxRunes]
	}
	return strings.TrimSpace(string(runes))
}

func phpSingleQuoted(s string) string {
	escaped := strings.ReplaceAll(s, `\`, `\\`)
	escaped = strings.ReplaceAll(escaped, `'`, `\'`)
	return "'" + escaped + "'"
}

func renderBundledDefaultsPHP(origin, slug, propName, primaryHex, primaryOnHex string) string {
	return fmt.Sprintf(`<?php
/**
 * Pre-configured property defaults generated by Lovelace Admin Console.
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

function lovelace_booking_bundled_defaults() {
	return array(
		'booking_origin'   => %s,
		'property_slug'    => %s,
		'property_name'    => %s,
		'primary_color'    => %s,
		'primary_on_color' => %s,
		'button_label'     => 'Book Direct',
		'default_mode'     => 'modal',
		'cache_ttl'        => 600,
	);
}
`,
		phpSingleQuoted(origin),
		phpSingleQuoted(slug),
		phpSingleQuoted(propName),
		phpSingleQuoted(primaryHex),
		phpSingleQuoted(primaryOnHex),
	)
}
